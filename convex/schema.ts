import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import { provider, phase, externalAccount, session } from "./preflightContract";
import { batchTables } from "./batchSchema";
import { batchChatTables } from "./batchChatSchema";
import { appleDisposition, executionPhase, executionSession } from "./clerkExecutionContract";
import { appleIdentity, executionProvider } from "./providerExecutionContract";

export const message = v.object({ role: v.union(v.literal("user"), v.literal("assistant")), text: v.string() });
const reservation = v.object({ bucket: v.id("quotaBuckets"), seconds: v.number(), questions: v.number() });
export default defineSchema({
  ...batchTables,
  ...batchChatTables,
  deletionProviderExecutions: defineTable({ request: v.id("deletions"), owner: v.string(), subject: v.string(), requestedAt: v.number(),
    provider: executionProvider, stage: v.id("deletionStages"), stageFence: v.number(), config: v.string(),
    safetyEvidence: v.string(), apple: v.optional(appleIdentity),
    clerkStage: v.optional(v.id("deletionStages")), clerkFence: v.optional(v.number()),
    phase: v.union(v.literal("execute"), v.literal("observe")),
    state: v.union(v.literal("queued"), v.literal("running"), v.literal("retry"), v.literal("blocked"), v.literal("exhausted"), v.literal("observed"), v.literal("manual")),
    fence: v.number(), attempts: v.number(), claims: v.number(), due: v.number(), leaseUntil: v.optional(v.number()),
    mutationIntent: v.boolean(), acknowledged: v.boolean(), absenceObserved: v.boolean(),
    code: v.string(), evidence: v.optional(v.string()), createdAt: v.number(), updatedAt: v.number(),
  }).index("by_request_provider", ["request", "provider"]).index("by_provider_state_due", ["provider", "state", "due"]),
  deletionClerkExecutions: defineTable({ request: v.id("deletions"), owner: v.string(), subject: v.string(), requestedAt: v.number(),
    stage: v.id("deletionStages"), stageFence: v.number(), config: v.string(),
    appleStage: v.id("deletionStages"), appleFence: v.number(), appleEvidence: v.string(), appleDisposition,
    phase: executionPhase, state: v.union(v.literal("queued"), v.literal("running"), v.literal("retry"),
      v.literal("blocked"), v.literal("exhausted"), v.literal("observed"), v.literal("manual")),
    sessions: v.array(executionSession), offset: v.number(), sessionIndex: v.number(), inventoryComplete: v.boolean(),
    mutationUncertain: v.boolean(), userDeleteAcknowledged: v.boolean(), userAbsenceObserved: v.boolean(),
    googleConfig: v.optional(v.string()),
    googleAccounts: v.optional(v.array(v.object({ externalAccountId: v.string(), providerUserId: v.string(), acknowledged: v.boolean(), evidence: v.optional(v.string()) }))),
    googleIndex: v.optional(v.number()), googleComplete: v.optional(v.boolean()),
    googleEvidence: v.optional(v.string()), googleNotApplicable: v.optional(v.boolean()),
    googleOperatorEvidence: v.optional(v.string()),
    fence: v.number(), attempts: v.number(), claims: v.number(), due: v.number(), leaseUntil: v.optional(v.number()),
    code: v.string(), evidence: v.optional(v.string()), createdAt: v.number(), updatedAt: v.number(),
  }).index("by_request", ["request"]).index("by_state_due", ["state", "due"]),
  deletionPreflights: defineTable({ request: v.id("deletions"), owner: v.string(), subject: v.string(),
    requestedAt: v.number(), provider, config: v.string(), phase, cursor: v.string(),
    state: v.union(v.literal("queued"), v.literal("running"), v.literal("retry"), v.literal("observed"), v.literal("blocked"), v.literal("exhausted")),
    code: v.string(), inventoryComplete: v.boolean(), fence: v.number(), attempts: v.number(), claims: v.number(),
    pages: v.number(), due: v.number(), leaseUntil: v.optional(v.number()), createdAt: v.number(), updatedAt: v.number(),
    purgeAt: v.optional(v.number()),
    externalAccounts: v.array(externalAccount), sessions: v.array(session), aliases: v.array(v.string()), cursors: v.array(v.string()),
  }).index("by_request_provider", ["request", "provider"]).index("by_state_due", ["state", "due"]).index("by_purge_at", ["purgeAt"]),
  deletionPreflightReceipts: defineTable({ request: v.id("deletions"), provider, state: v.string(), code: v.string(),
    inventoryComplete: v.boolean(), createdAt: v.number(), updatedAt: v.number(), purgedAt: v.number(),
  }).index("by_request_provider", ["request", "provider"]),
  deletionReceipts: defineTable({ completedAt: v.number(), purgedAt: v.number(),
    policy: v.literal("completed_90d_v1"),
  }),
  deletionContacts: defineTable({ request: v.id("deletions"), owner: v.string(), subject: v.string(),
    issuer: v.string(), instance: v.string(), email: v.optional(v.string()), code: v.string(), capturedAt: v.number(),
  }).index("by_request", ["request"]),
  deletionSends: defineTable({ request: v.id("deletions"), intent: v.id("deletionOutbox"), revision: v.number(),
    owner: v.string(), subject: v.string(), recipient: v.string(), contact: v.id("deletionContacts"),
    completion: v.object({ localComplete: v.literal(true), clerk: v.literal(true), apple: v.literal(true),
      revenuecat: v.literal(true), gemini: v.literal(true), residuals: v.literal(true) }),
    config: v.string(), payload: v.string(), key: v.string(), createdAt: v.number(),
    state: v.union(v.literal("queued"), v.literal("running"), v.literal("retry"), v.literal("pending"), v.literal("exception")),
    delivery: v.literal("pending"), code: v.string(), attempts: v.number(), fence: v.number(), due: v.number(),
    firstAttemptAt: v.optional(v.number()), leaseUntil: v.optional(v.number()), providerId: v.optional(v.string()),
  }).index("by_request", ["request"]).index("by_state_due", ["state", "due"]),
  deletions: defineTable({ owner: v.string(), subject: v.string(), requestedAt: v.number(),
    localComplete: v.boolean(),
    googleRequired: v.optional(v.boolean()),
    googleStatus: v.optional(v.union(v.literal("pending"), v.literal("revoking"), v.literal("acknowledged"),
      v.literal("exception"), v.literal("not_applicable"), v.literal("unknown"))),
    // Retain bounded proof until this ledger is purged, including child-batch cleanup.
    googleEvidence: v.optional(v.string()),
    clerk: v.boolean(), revenuecat: v.boolean(), apple: v.boolean(), gemini: v.boolean(), residuals: v.boolean(),
    clerkEvidence: v.optional(v.string()), revenuecatEvidence: v.optional(v.string()),
    appleEvidence: v.optional(v.string()), geminiEvidence: v.optional(v.string()), residualsEvidence: v.optional(v.string()),
    updatedAt: v.number(), evidence: v.optional(v.string()),
    automationRevision: v.optional(v.number()), discoveryComplete: v.optional(v.boolean()), discoveryEpoch: v.optional(v.number()),
    completedAt: v.optional(v.number()), purgeAt: v.optional(v.number()),
  }).index("by_owner", ["owner"]).index("by_purge_at", ["purgeAt"]),
  deletionStages: defineTable({
    request: v.id("deletions"), owner: v.string(), key: v.string(),
    kind: v.union(v.literal("geminiFile"), v.literal("clerk"), v.literal("apple"), v.literal("revenuecat"), v.literal("gemini"), v.literal("residuals")),
    target: v.string(), config: v.string(), work: v.optional(v.id("deletionWork")),
    state: v.union(v.literal("queued"), v.literal("running"), v.literal("retry"), v.literal("succeeded"), v.literal("blocked"), v.literal("exhausted"), v.literal("manual")),
    fence: v.number(), attempts: v.number(), nextAttemptAt: v.number(), leaseUntil: v.optional(v.number()),
    code: v.optional(v.string()), httpStatus: v.optional(v.number()), evidence: v.optional(v.string()), updatedAt: v.number(),
  }).index("by_request_key", ["request", "key"]).index("by_request_state", ["request", "state"])
    .index("by_state_due", ["state", "nextAttemptAt"]).index("by_work", ["work"]),
  deletionOutbox: defineTable({ request: v.id("deletions"), owner: v.string(), revision: v.number(),
    kind: v.literal("scope_status"), state: v.literal("intent"), delivery: v.literal("not_configured"),
    classification: v.union(v.literal("queued"), v.literal("exceptions"), v.literal("scope_complete")),
    localComplete: v.boolean(), providersComplete: v.boolean(), updatedAt: v.number(),
  }).index("by_request", ["request"]),
  deletionWork: defineTable({ owner: v.string(), kind: v.union(v.literal("upload"), v.literal("gemini"), v.literal("chat"), v.literal("billing")),
    startedAt: v.number(), finished: v.boolean(),
    audio: v.optional(v.id("_storage")), file: v.optional(v.string()),
    fileDeleted: v.optional(v.boolean()), ambiguous: v.boolean(),
    knowledgeVersion: v.optional(v.literal(1)), providerConfig: v.optional(v.string()),
    generationStarted: v.optional(v.boolean()), generationFinished: v.optional(v.boolean()),
  }).index("by_owner", ["owner"]),
  billingAccounts: defineTable({ owner: v.string(), subject: v.string(), revision: v.number(),
    observedAt: v.optional(v.number()), verifiedAt: v.optional(v.number()),
    plan: v.optional(v.union(v.literal("free"), v.literal("pro"))),
    expiresAt: v.optional(v.union(v.number(), v.null())), anchor: v.optional(v.number()),
  }).index("by_owner", ["owner"]),
  quotaBuckets: defineTable({ owner: v.string(), window: v.string(), secondsUsed: v.number(), secondsReserved: v.number(),
    questionsUsed: v.number(), questionsReserved: v.number(),
  }).index("by_owner_window", ["owner", "window"]),
  recordings: defineTable({
    owner: v.string(),
    audio: v.id("_storage"),
    mimeType: v.string(),
    status: v.union(v.literal("queued"), v.literal("processing"), v.literal("ready"), v.literal("failed")),
    transcript: v.optional(v.string()),
    messages: v.array(message),
    error: v.optional(v.string()),
    chatLease: v.optional(v.string()),
    subject: v.optional(v.string()),
    jobDeadline: v.optional(v.number()),
    chatDeadline: v.optional(v.number()),
    transcriptionReservation: v.optional(reservation),
    chatReservation: v.optional(reservation),
  }).index("by_owner", ["owner"]),
});
